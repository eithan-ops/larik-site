/** מגריל זוג לפי רמת קושי; מחזיר [מילת הרוב, מילת המתחזה] בסדר אקראי. */
export function pickUndercoverPair(level: "normal" | "hard", used: Set<string>): { pair: [string, string]; key: string } {
  const wanted = level === "hard" ? 1 : 2;
  let pool = UNDERCOVER_PAIRS.filter((p) => p.d === wanted && !used.has(p.a + "|" + p.b));
  if (!pool.length) {
    used.clear();
    pool = UNDERCOVER_PAIRS.filter((p) => p.d === wanted);
  }
  const p = pool[Math.floor(Math.random() * pool.length)];
  const key = p.a + "|" + p.b;
  used.add(key);
  // מי מהשניים הוא "מילת הרוב" מתחלף — אחרת אפשר ללמוד את החפיסה
  return { pair: Math.random() < 0.5 ? [p.a, p.b] : [p.b, p.a], key };
}
